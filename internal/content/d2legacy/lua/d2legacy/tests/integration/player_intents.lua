local player = require("d2legacy.player_intents")
player.assign_skill("right", 17)
player.request_skill("right", 20.5, 30.25, "fallen:7")
player.request_move(12, 13)
assert(player.movement_pending(), "ground route was not queued")
player.request_skill("right", 20.5, 30.25, "fallen:7")
assert(player.movement_pending(), "right skill changed the existing pointer route")
player.request_skill("left", 20.5, 30.25, "fallen:7")
assert(not player.movement_pending(), "left attack retained the old ground route")
player.request_skill("left", 20.5, 30.25, "fallen:7")
assert(not player.movement_pending(), "held left attack restored the old ground route")
player.request_move(14, 15)
assert(player.movement_pending(), "new ground movement did not replace the attack")
